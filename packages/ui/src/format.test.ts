import { describe, expect, it } from 'vitest';
import { plural } from './format.js';

describe('plural', () => {
  it('1, 2–4, 5–20, 21, 111', () => {
    const f = (n: number) => plural(n, 'нажатие', 'нажатия', 'нажатий');
    expect([1, 2, 4, 5, 11, 12, 14, 20, 21, 22, 25, 111, 101].map(f)).toEqual([
      'нажатие', 'нажатия', 'нажатия', 'нажатий', 'нажатий', 'нажатий', 'нажатий', 'нажатий', 'нажатие', 'нажатия', 'нажатий', 'нажатий', 'нажатие',
    ]);
  });
});
